1. РЕГИСТР СТРОК
================

strtoupper($str)
  $str — исходная строка
  Возвращает: строку в ВЕРХНЕМ регистре (латиница)

strtolower($str)
  $str — исходная строка
  Возвращает: строку в нижнем регистре (латиница)

ucfirst($str)
  $str — исходная строка
  Возвращает: строку, где ПЕРВАЯ буква строки — заглавная

lcfirst($str)
  $str — исходная строка
  Возвращает: строку, где ПЕРВАЯ буква строки — строчная

ucwords($str)
  $str — исходная строка
  Возвращает: строку, где ПЕРВАЯ буква КАЖДОГО слова — заглавная

mb_strtoupper($str, $encoding)
  $str — исходная строка
  $encoding — кодировка (например, 'UTF-8')
  Возвращает: строку в ВЕРХНЕМ регистре (для кириллицы)

mb_strtolower($str, $encoding)
  $str — исходная строка
  $encoding — кодировка ('UTF-8')
  Возвращает: строку в нижнем регистре (для кириллицы)

mb_convert_case($str, $mode, $encoding)
  $str — исходная строка
  $mode — режим: MB_CASE_TITLE (каждое слово), MB_CASE_UPPER (всё верх), MB_CASE_LOWER (всё низ)
  $encoding — кодировка ('UTF-8')
  Возвращает: преобразованную строку (для кириллицы)

2. ПОИСК В СТРОКЕ
=================

strpos($str, $needle, $offset)
  $str — строка, в которой ищем
  $needle — что ищем (подстрока)
  $offset — с какого символа начинать поиск (необязательно, по умолчанию 0)
  Возвращает: индекс ПЕРВОГО вхождения или false, если не найдено

strrpos($str, $needle, $offset)
  $str — строка, в которой ищем
  $needle — что ищем
  $offset — с какого символа начинать поиск (необязательно)
  Возвращает: индекс ПОСЛЕДНЕГО вхождения или false

stripos($str, $needle, $offset)
  $str — строка, в которой ищем
  $needle — что ищем
  $offset — с какого символа начинать (необязательно)
  Возвращает: индекс первого вхождения БЕЗ учёта регистра или false

strstr($str, $needle, $before)
  $str — строка, в которой ищем
  $needle — что ищем
  $before — true: вернуть часть ДО подстроки; false/не указано: вернуть часть ОТ подстроки
  Возвращает: часть строки или false

strpbrk($str, $chars)
  $str — строка, в которой ищем
  $chars — набор символов (строка), любой из которых ищем
  Возвращает: часть строки, начиная с первого найденного символа из набора, или false

substr_count($str, $needle)
  $str — строка, в которой считаем
  $needle — что считаем
  Возвращает: число вхождений подстроки

3. ВЫРЕЗАНИЕ ЧАСТИ СТРОКИ
=========================

substr($str, $start, $length)
  $str — исходная строка
  $start — с какого символа начать (0 — первый, -1 — последний)
  $length — сколько символов взять (необязательно; если не указано — до конца)
  Возвращает: вырезанную часть строки

substr($str, $start)
  $str — строка
  $start — с какого символа
  Возвращает: часть строки с $start до конца

substr($str, -$n)
  $str — строка
  -$n — отрицательное число: отсчёт с конца
  Возвращает: последние $n символов

substr($str, 0, $n)
  $str — строка
  0 — с начала
  $n — сколько символов
  Возвращает: первые $n символов

4. ЗАМЕНА В СТРОКЕ
==================

str_replace($search, $replace, $str)
  $search — что ищем (точная подстрока)
  $replace — на что заменяем (пустая строка '' — удаляем)
  $str — исходная строка
  Возвращает: строку с заменами

preg_replace($pattern, $replace, $str, $limit)
  $pattern — регулярное выражение (в слэшах: '/шаблон/')
  $replace — на что заменяем
  $str — исходная строка
  $limit — сколько замен сделать (необязательно; по умолчанию — все)
  Возвращает: строку с заменами

preg_replace_callback($pattern, $callback, $str)
  $pattern — регулярное выражение
  $callback — функция, которая обрабатывает каждое найденное
  $str — исходная строка
  Возвращает: строку с заменами

5. УДАЛЕНИЕ ПРОБЕЛОВ
====================

ltrim($str)
  $str — исходная строка
  Возвращает: строку без пробелов СЛЕВА

rtrim($str)
  $str — исходная строка
  Возвращает: строку без пробелов СПРАВА

trim($str)
  $str — исходная строка
  Возвращает: строку без пробелов С ОБЕИХ СТОРОН

6. РАЗБИЕНИЕ И СКЛЕЙКА
======================
explode($sep, $str)
  $sep — разделитель (по какому символу разбивать)
  $str — исходная строка
  Возвращает: МАССИВ частей

implode($sep, $arr)
  $sep — разделитель (чем соединять)
  $arr — массив
  Возвращает: строку

str_split($str, $length)
  $str — исходная строка
  $length — длина каждой части (по умолчанию 1)
  Возвращает: МАССИВ частей

mb_str_split($str, $length, $encoding)
  $str — исходная строка
  $length — длина каждой части (обычно 1)
  $encoding — кодировка ('UTF-8')
  Возвращает: МАССИВ символов

7. ПЕРЕВОРОТ СТРОКИ
===================

strrev($str)
  $str — исходная строка
  Возвращает: перевёрнутую строку (латиница)

str_shuffle($str)
  $str — исходная строка
  Возвращает: строку с перемешанными символами (латиница)

Для кириллицы:
  preg_split('//u', $str, -1, PREG_SPLIT_NO_EMPTY)
    '//u' — шаблон для разбиения на UTF-8 символы
    -1 — без ограничения
    PREG_SPLIT_NO_EMPTY — не включать пустые элементы
    Возвращает: МАССИВ символов
  array_reverse($arr) — переворачивает массив
  implode('', $arr) — склеивает в строку

