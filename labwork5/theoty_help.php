11. ФОРМАТИРОВАНИЕ
==================

sprintf($format, $arg1, $arg2, ...)
  $format — шаблон с местами для подстановки
  $arg1, $arg2, ... — значения для подстановки
  Возвращает: отформатированную строку

printf($format, $arg1, $arg2, ...)
  $format — шаблон
  $arg1, $arg2, ... — значения
  Выводит: отформатированную строку

vsprintf($format, $arr)
  $format — шаблон
  $arr — МАССИВ значений
  Возвращает: отформатированную строку

str_pad($str, $length, $pad, $type)
  $str — исходная строка
  $length — до какой длины дополнить
  $pad — чем дополнить (например, '0' или ' ')
  $type — куда: STR_PAD_LEFT (слева), STR_PAD_RIGHT (справа), STR_PAD_BOTH (с обеих)
  Возвращает: дополненную строку

Форматы:
  %02d — целое, минимум 2 цифры, дополнение нулём
  %s — строка
  %f — дробное

12. РЕГУЛЯРНЫЕ ВЫРАЖЕНИЯ (ОСНОВЫ)
==================================

[^0-9] — всё, кроме цифр
[^0-9\s] — всё, кроме цифр и пробелов
\d — цифра
\w — буква или цифра
\s — пробел
+ — один или несколько
* — ноль или несколько
$ — конец строки
^ — начало строки
\b — граница слова

